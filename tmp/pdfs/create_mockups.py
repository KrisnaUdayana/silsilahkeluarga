class SVG:
    def __init__(self,w,h):
        self.a=[f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="{w}" height="{h}" viewBox="0 0 {w} {h}"><defs><filter id="shadow" x="-40%" y="-40%" width="180%" height="180%"><feDropShadow dx="0" dy="18" stdDeviation="20" flood-color="#182F24" flood-opacity="0.16"/></filter></defs>']
        self.rect(0,0,w,h,cream)
    def rect(self,x,y,w,h,c,r=0,stroke=None):
        self.a.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{c}"'+(f' stroke="{stroke}"' if stroke else '')+'/>')
    def text(self,x,y,s,size=16,c=ink,font='Arial',weight='normal',extra=''):
        self.a.append(f'<text x="{x}" y="{y}" font-family="{font}" font-size="{size}" font-weight="{weight}" fill="{c}" {extra}>{html.escape(s)}</text>')
    def lines(self,x,y,ss,size=16,c=muted,font='Arial',gap=26):
        for i,s in enumerate(ss):self.text(x,y+i*gap,s,size,c,font)
    def rule(self,x,y,w,c=line):self.a.append(f'<path d="M{x} {y}h{w}" stroke="{c}"/>')
    def img(self,x,y,w,h,u,shadow=False):self.a.append(f'<image x="{x}" y="{y}" width="{w}" height="{h}" href="{u}"'+(' filter="url(#shadow)"' if shadow else '')+'/>')
    def btn(self,x,y,w,label,primary=True):
        self.rect(x,y,w,48,ink if primary else cream,6,None if primary else line)
        self.text(x+20,y+30,label,14,'#FFFDF6' if primary else ink,weight='bold')
        self.text(x+w-31,y+30,'→',18,'#FFFDF6' if primary else ink)
    def tag(self,x,y,s):self.text(x,y,s,11,gold,weight='bold',extra='letter-spacing="2"')
    def save(self,name):
        self.a.append('</svg>');(out/name).write_text('\n'.join(self.a),encoding='utf-8')
